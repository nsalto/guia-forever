local SPEC_ORDER = {
  WARRIOR = { "arms", "fury", "prot" }, PALADIN = { "ret", "prot", "holy" }, HUNTER = { "bm", "mm", "surv" },
  ROGUE = { "combat", "assassination", "subtlety", "bleed" }, PRIEST = { "disc", "shadow", "holy" },
  SHAMAN = { "enh", "ele", "resto" }, MAGE = { "frost", "fire", "arcane" }, WARLOCK = { "aff", "demo", "destro" },
  DRUID = { "feral", "bear", "balance", "resto" },
}
local CONF = { high = "alta", medium = "media", low = "baja" }
local ROLES = { dps = "daño", tank = "tanque", heal = "sanación" }

for class, specs in pairs(SPEC_DATA or {}) do
  local cd = G.classes[class]
  if cd then
    cd.specs = cd.specs or {}
    cd.specOrder = cd.specOrder or {}
    for _, key in ipairs(SPEC_ORDER[class] or {}) do
      local src = specs[key]
      if src then
        local sp = cd.specs[key]
        if not sp then
          sp = { label = src.label, pitch = src.pitch, talents = src.talents }
          cd.specs[key] = sp
          local present = false
          for _, k in ipairs(cd.specOrder) do if k == key then present = true end end
          if not present then cd.specOrder[#cd.specOrder + 1] = key end
        end
        if not sp.rating then
          sp.rating = src.rating
          sp.build60 = sp.build60 or src.build60
          sp.confidence = sp.confidence or CONF[src.confidence] or src.confidence
          sp.endgame = sp.endgame or src.note
        end
        sp.capstone = sp.capstone or src.capstone
        sp.stats = sp.stats or src.stats
        sp.roles = sp.roles or (src.roles and (ROLES[src.roles] or src.roles))
        -- Rogue keeps its hand-written talent list; other classes take the researched one (it has notes and levels).
        if src.talents and (class ~= "ROGUE" or not sp.talents or #sp.talents == 0) then sp.talents = src.talents end
      end
    end
    cd.ratingNote = cd.ratingNote or "Rankings del 60 provisorios: la beta llegaba al 30 y las bandas abren el 9/12. Fuentes: guías y tier lists de Forever (nov 2026)."
    if cd.defaultSpec and not cd.specs[cd.defaultSpec] then cd.defaultSpec = cd.specOrder[1] end
  end
end
